# frozen_string_literal: true

require "rails_helper"

RSpec.describe Git::AuthorizedKeysWriter do
  let(:user) { users(:one) }
  let!(:key1) do
    user.ssh_public_keys.create!(
      name: "laptop",
      public_key: "ssh-ed25519 AAAAFIRST user@host",
      fingerprint: "SHA256:#{SecureRandom.hex(8)}"
    )
  end
  let!(:key2) do
    user.ssh_public_keys.create!(
      name: "desktop",
      public_key: "ssh-ed25519 AAAASECOND user@desk",
      fingerprint: "SHA256:#{SecureRandom.hex(8)}"
    )
  end

  it "render includes a banner" do
    expect(described_class.render).to match(/AUTOGENERATED BY Git::AuthorizedKeysWriter/)
  end

  it "render emits one line per key with forced command + key id environment" do
    out = described_class.render

    expect(out).to match(%r{command="/opt/wokku/bin/wokku-git-shell"})
    expect(out).to match(/no-pty/)
    expect(out).to match(/no-port-forwarding/)
    expect(out).to match(/environment="WOKKU_GIT_KEY_ID=#{key1.id}"/)
    expect(out).to match(/environment="WOKKU_GIT_KEY_ID=#{key2.id}"/)
    expect(out).to match(/ssh-ed25519 AAAAFIRST/)
    expect(out).to match(/ssh-ed25519 AAAASECOND/)
  end

  it "render strips whitespace-only noise from stored pubkeys" do
    key = user.ssh_public_keys.create!(
      name: "messy", public_key: "  ssh-ed25519   AAAAMESSY  user@h\n",
      fingerprint: "SHA256:#{SecureRandom.hex(8)}"
    )
    line = described_class.render(scope: SshPublicKey.where(id: key.id))
    expect(line.strip).to match(/ssh-ed25519 AAAAMESSY user@h$/)
    expect(line).not_to match(/\n\s+ssh/)
  end

  it "write! no-ops when no path configured" do
    ENV.delete("WOKKU_GIT_AUTHORIZED_KEYS_PATH")
    expect(described_class.write!).to be_nil
  end

  it "write! writes content atomically when path is configured" do
    Dir.mktmpdir do |dir|
      path = File.join(dir, "sub", "authorized_keys")
      result = described_class.write!(path: path)
      expect(result).to eq(path)
      expect(File.exist?(path)).to be_truthy
      expect(File.read(path)).to match(/ssh-ed25519 AAAAFIRST/)
      expect(File.stat(path).mode & 0o777).to eq(0o600)
    end
  end

  it "write! is idempotent" do
    Dir.mktmpdir do |dir|
      path = File.join(dir, "authorized_keys")
      described_class.write!(path: path)
      first_content = File.read(path)
      described_class.write!(path: path)
      expect(File.read(path)).to eq(first_content)
    end
  end
end
